'use strict';

// One-off harness: loads the repo's global-scope scripts in Node, registers a
// minimal "opaque" entity type (normally done by webgl_init() in a browser),
// and snapshots the default football pitch entities.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const repo = path.resolve(__dirname, '..');

// Browser globals the repo scripts expect at load time; never fired here.
globalThis.addEventListener = () => {};
globalThis.removeEventListener = () => {};
globalThis.TouchEvent = class TouchEvent {};

const files = [
  'js/math.js',
  'js/core.js',
  'js/entity.js',
  'js/webgl.js',
  'js/prefabs/webgl.js',
];
for(const file of files){
  vm.runInThisContext(fs.readFileSync(path.join(repo, file), 'utf8'), {
    'filename': file,
  });
}

// Minimal stand-in for the "opaque" entity type registered in webgl_init().
entity_set({
  'defaults': true,
  'properties': {
    'alpha': 1,
    'attach_to': '',
    'attach_x': 0,
    'attach_y': 0,
    'attach_z': 0,
    'billboard': false,
    'collision': true,
    'draw': true,
    'draw_mode': 'TRIANGLE_FAN',
    'groups': [],
    'picking': false,
    'position_x': 0,
    'position_y': 0,
    'position_z': 0,
    'rotate_x': 0,
    'rotate_y': 0,
    'rotate_z': 0,
    'texture': 'default.png',
    'vertex_colors': [],
    'vertices': [],
  },
  'type': 'opaque',
});

prefabs_webgl_football_pitch({
  'prefix': 'default',
});

const snapshot = {};
for(const id in entity_entities){
  snapshot[id] = [...entity_entities[id].vertices];
}
const snapshot_json = JSON.stringify(snapshot, null, 2) + '\n';
fs.writeFileSync(
  path.join(__dirname, 'football_pitch_default_entities.json'),
  snapshot_json
);
// Browser-global form used by football_pitch.htm.
fs.writeFileSync(
  path.join(__dirname, 'football_pitch_default_entities.js'),
  "'use strict';\n"
    + '// Generated by test/capture_default.js from an unmodified default '
    + 'prefab call.\n'
    + 'globalThis.football_pitch_default_entities = '
    + snapshot_json
);
console.log('snapshot entity count:', Object.keys(snapshot).length);
